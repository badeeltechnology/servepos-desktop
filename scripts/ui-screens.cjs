async function newPage(browser, width, query = '?wo=none') {
  const page = await browser.newPage({ viewport: { width, height: 768 } })
  page.setDefaultTimeout(6000)
  current = page
  page.on('pageerror', (e) => errors.push(`[${width}] pageerror: ${e.message}`))
  page.on('console', (m) => { if (m.type() === 'error') errors.push(`[${width}] console: ${m.text()}`) })
  await page.goto(BASE + query)
  await page.waitForTimeout(700)
  return page
}
async function shot(page, name, suffix = '') {
  const w = page.viewportSize().width
  const file = path.join(OUT, `${name}-${w}${suffix}.png`)
  await page.waitForTimeout(250)
  await page.screenshot({ path: file })
  shots.push(path.basename(file))
}
async function pin(page, digits) {
  for (const d of digits) await page.getByRole('button', { name: d, exact: true }).first().click()
  await page.waitForTimeout(600)
}
async function step(name, fn) {
  try { await fn(); console.log('  ok  ', name) } catch (e) {
    failures.push(`${name}: ${e.message.split('\n')[0]}`)
    console.log('  FAIL', name, '-', e.message.split('\n').slice(0, 3).join(' | '))
    if (process.env.FAILSHOTS && current) await current.screenshot({ path: path.join(OUT, `fail-${failures.length}.png`) }).catch(() => {})
  }
}
