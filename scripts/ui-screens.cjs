/** Pay: dine-in without a table → "Takeaway instead"; unsent lines → "Send and pay"; until the payment screen is up. */
async function pay(page, { takeaway = true } = {}) {
  await page.getByRole('button', { name: /^(Send & pay|Pay)/ }).first().click()
  for (let i = 0; i < 40; i++) {
    if (await page.getByRole('dialog', { name: 'Payment' }).isVisible()) return
    const ti = page.getByRole('button', { name: 'Takeaway instead', exact: true })
    if (takeaway && await ti.isVisible()) { await ti.click(); continue }
    const sp = page.getByRole('button', { name: 'Send and pay', exact: true })
    if (await sp.isVisible()) { await sp.click(); continue }
    await page.waitForTimeout(150)
  }
  throw new Error('payment screen did not open')
}

